#pragma once
// What counts as test code, for every analysis that leaves it out (docs/diagnose.md). Internal.

#include <sstream>
#include <string>
#include <cctype>
#include <string_view>
#include <vector>

namespace optum {

// A node id or a file path is test code if a segment (split at ':', '.', '/', '#') is test,
// tests, testing, spec or __tests__, or starts with test_ or ends with _test / _tests. That covers
// test_*.py, *_test.go, tests/..., *.test.js and *.spec.ts.
inline bool is_test_code(std::string_view id) {
  const auto colon = id.find(':');
  std::string rest(colon == std::string_view::npos ? id : id.substr(colon + 1));
  for (char& c : rest) {
    if (c == '.' || c == '/' || c == '#') c = ' ';
  }
  std::istringstream words(rest);
  for (std::string w; words >> w;) {
    if (w == "test" || w == "tests" || w == "testing" || w == "spec" || w == "__tests__" ||
        w.starts_with("test_") || w.ends_with("_test") || w.ends_with("_tests")) {
      return true;
    }
  }
  return false;
}

}  // namespace optum

namespace optum {

// Code that isn't the project's own (docs/diagnose.md, "Whose code"): "vendored" (vendor/,
// _vendor/, third_party/, deps/, external/...), "build" (dist/, build/, minified or bundled JS) or
// "example" (examples/, samples/, demo/). Empty for the project's own code. By directory, so a
// module named build.py stays the project's.
inline std::string code_area(std::string_view path) {
  std::vector<std::string> segs;
  std::string cur;
  for (char c : path) {
    if (c == '/' || c == '\\') {
      if (!cur.empty()) segs.push_back(cur);
      cur.clear();
    } else {
      cur += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    }
  }
  const std::string file = cur;
  if (file.ends_with(".min.js") || file.ends_with(".bundle.js") || file.ends_with("-bundle.js")) return "build";
  for (const auto& s : segs) {
    if (s == "vendor" || s == "vendored" || s == "_vendor" || s == "third_party" || s == "thirdparty" ||
        s == "third-party" || s == "deps" || s == "external" || s == "externals" || s == "extern" ||
        s == "bower_components" || s == "jspm_packages") {
      return "vendored";
    }
    if (s == "dist" || s == "build" || s == "_build") return "build";
    if (s == "examples" || s == "example" || s == "samples" || s == "sample" || s == "demo" || s == "demos") {
      return "example";
    }
  }
  return "";
}

// A file that says it's generated: a comment line (#, //, /*, *, --) in its first 10 lines with
// "@generated", "do not edit", or "generated" with "by" / "automatically" / "auto" ("Code generated
// by protoc-gen-go. DO NOT EDIT.", "# *** GENERATED BY `python -m ...` ***"). Only comments at the
// top count: prose and docstrings ("the group generated by reflections") don't.
inline bool generated_header(std::string_view head) {
  std::size_t pos = 0;
  for (int line = 0; line < 10 && pos < head.size(); ++line) {
    const std::size_t nl = head.find('\n', pos);
    std::string_view l = head.substr(pos, nl == std::string_view::npos ? std::string_view::npos : nl - pos);
    pos = nl == std::string_view::npos ? head.size() : nl + 1;
    while (!l.empty() && (l.front() == ' ' || l.front() == '\t')) l.remove_prefix(1);
    const bool comment = l.starts_with("#") || l.starts_with("//") || l.starts_with("/*") || l.starts_with("*") ||
                         l.starts_with("--");
    if (!comment || l.starts_with("#include") || l.starts_with("#define") || l.starts_with("#!")) continue;
    std::string low(l);
    for (char& c : low) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    if (low.find("@generated") != std::string::npos || low.find("do not edit") != std::string::npos) return true;
    if (low.find("generated") != std::string::npos &&
        (low.find("generated by") != std::string::npos || low.find("automatically") != std::string::npos ||
         low.find("auto-generated") != std::string::npos || low.find("autogenerated") != std::string::npos)) {
      return true;
    }
  }
  return false;
}

}  // namespace optum
